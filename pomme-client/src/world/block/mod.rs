/// Compact per-state property map: `(key, value)` pairs sorted by key. States
/// have at most ~10 properties, so binary search on a boxed slice beats a
/// `HashMap` in both footprint and lookup cost.
pub struct PropMap(Box<[(&'static str, &'static str)]>);

impl PropMap {
    fn from_pairs(mut pairs: Vec<(&'static str, &'static str)>) -> Self {
        pairs.sort_unstable_by_key(|&(k, _)| k);
        Self(pairs.into_boxed_slice())
    }

    pub fn get(&self, key: &str) -> Option<&'static str> {
        self.0
            .binary_search_by_key(&key, |&(k, _)| k)
            .ok()
            .map(|i| self.0[i].1)
    }

    pub fn entries(&self) -> impl Iterator<Item = (&'static str, &'static str)> + '_ {
        self.0.iter().copied()
    }
}

/// The two behavior fields the client reads (from vanilla `BlockBehaviour`).
#[derive(Clone, Copy)]
pub struct BlockBehavior {
    pub destroy_time: f32,
    pub requires_correct_tool_for_drops: bool,
}

const DEFAULT_BEHAVIOR: BlockBehavior = BlockBehavior {
    destroy_time: 0.0,
    requires_correct_tool_for_drops: false,
};

/// A face-occlusion shape projected onto the face plane as a 16x16 bit grid;
/// `mask[v]` holds row `v`'s bits. Generated by `just stategen`.
pub type FaceMask = [u16; 16];

/// Per-state light properties (vanilla `BlockBehaviour.BlockStateBase`'s
/// baked light cache), loaded from the per-version table generated by
/// `tools/stategen` running vanilla's own code.
#[derive(Clone, Copy)]
pub struct LightProps {
    pub emission: u8,
    pub dampening: u8,
    /// Unconsumed at runtime (vanilla only folds it into `dampening` at
    /// bake time); carried for parity with the vanilla property set.
    #[allow(dead_code)]
    pub propagates_skylight_down: bool,
    pub can_occlude: bool,
    pub use_shape_for_light_occlusion: bool,
    /// Per-face occlusion masks in vanilla `Direction` ordinal order (DOWN,
    /// UP, NORTH, SOUTH, WEST, EAST); `Some` exactly when `can_occlude &&
    /// use_shape_for_light_occlusion`.
    pub face_occlusion: Option<&'static [FaceMask; 6]>,
}

/// Unknown states occlude fully, matching vanilla's bedrock fallback for
/// out-of-range light-engine reads.
const BEDROCK_LIGHT: LightProps = LightProps {
    emission: 0,
    dampening: 15,
    propagates_skylight_down: false,
    can_occlude: true,
    use_shape_for_light_occlusion: false,
    face_occlusion: None,
};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum FluidKind {
    Empty,
    Water,
    Lava,
}

/// Fluid content of a block state, matching vanilla `FluidState`: sources and
/// waterlogged blocks are amount 8; flowing fluid is `8 - level`; falling
/// fluid (level >= 8) renders/behaves as a full column.
#[derive(Clone, Copy)]
pub struct Fluid {
    pub kind: FluidKind,
    pub amount: u8,
    /// Not consumed yet; kept for vanilla parity (falling columns behave as
    /// full sources in flow/height logic).
    #[allow(dead_code)]
    pub falling: bool,
}

const NO_FLUID: Fluid = Fluid {
    kind: FluidKind::Empty,
    amount: 0,
    falling: false,
};

const FULL_WATER: Fluid = Fluid {
    kind: FluidKind::Water,
    amount: 8,
    falling: false,
};

impl Fluid {
    pub fn height(&self) -> f32 {
        self.amount as f32 / 9.0
    }
}

/// Per-state block data loaded from the per-version table generated by
/// `tools/blockgen` from Mojang's data-generator report. Hot paths (meshing
/// classifies and textures every block) index this directly.
struct BlockData {
    id: &'static str,
    properties: PropMap,
    behavior: BlockBehavior,
    /// Collision shape; see `block_shape::partial_shape` for the encoding.
    /// Generated vanilla shapes are deduplicated and shared across states.
    shape: Option<&'static [LocalBox]>,
    /// Outline shape (vanilla `getShape`) where it differs from `shape`; `None`
    /// means the two agree and the collision shape doubles as the outline.
    outline: Option<&'static [LocalBox]>,
    is_air: bool,
    /// Vanilla `hasCollision` (`BlockBehaviour.Properties.noCollision()`).
    collides: bool,
    /// Vanilla `BlockState.blocksMotion()`, consumed by the follow-up fluid
    /// movement parity branch.
    #[allow(dead_code)]
    blocks_motion: bool,
    /// Vanilla cached `BlockState.isSolid()` / `legacySolid`, consumed by the
    /// follow-up fluid renderer branch.
    #[allow(dead_code)]
    legacy_solid: bool,
    /// Vanilla cached `BlockState.canBeReplaced()` property, consumed by the
    /// follow-up interaction prediction branch.
    #[allow(dead_code)]
    replaceable: bool,
    /// Packed Direction ordinal bits for
    /// `BlockState.isFaceSturdy(..., SupportType.FULL)`; consumed by collision
    /// and fluid renderer follow-ups.
    #[allow(dead_code)]
    full_face_sturdy: u8,
    /// Whether vanilla's logical collision/outline shape applies the state's
    /// generated positional offset. Legacy compatibility tables keep these
    /// false because they do not carry authoritative offset metadata.
    collision_shape_uses_offset: bool,
    outline_shape_uses_offset: bool,
    position_offset: Option<PositionOffset>,
    fluid: Fluid,
    light: LightProps,
}

#[derive(serde::Deserialize)]
struct BlockFile {
    version: String,
    state_count: u32,
    blocks: Vec<BlockEntry>,
}

// The data files also carry a `default_id` per block; nothing client-side
// consumes it yet, so serde skips it.
#[derive(serde::Deserialize)]
struct BlockEntry {
    name: String,
    first_id: u32,
    /// `(key, values)` in state-enumeration order; the last property varies
    /// fastest across consecutive state ids.
    #[serde(default)]
    props: Vec<(String, Vec<String>)>,
}

#[derive(serde::Deserialize)]
struct BehaviorEntry {
    destroy_time: f32,
    requires_correct_tool: bool,
}

#[derive(serde::Deserialize)]
struct StateFile {
    version: String,
    state_count: u32,
    /// Deduped face masks as 64-hex-char strings (16 rows of 4 chars).
    masks: Vec<String>,
    /// Deduped exact vanilla collision/outline shapes. Older generated tables
    /// omit this field and continue using the hand-computed fallback.
    #[serde(default)]
    shapes: Vec<Vec<f64>>,
    blocks: Vec<StateEntry>,
}

/// Per-block fields; each is a scalar when uniform across the block's
/// states, else one value per state. `f` is 6 mask-dictionary indices —
/// a single tuple when uniform, else a per-state list of tuple-or-null.
#[derive(serde::Deserialize)]
struct StateEntry {
    name: String,
    e: ScalarOrPerState,
    d: ScalarOrPerState,
    p: ScalarOrPerState,
    o: ScalarOrPerState,
    u: ScalarOrPerState,
    /// `hasCollision`; block-level in vanilla, so always a scalar.
    c: u8,
    /// Vanilla `BlockState.blocksMotion()`. Exact generated state tables carry
    /// `m/l/v/t` together; legacy embedded tables omit all four and are loaded
    /// only through the explicit compatibility mode below.
    #[serde(default)]
    m: Option<ScalarOrPerState>,
    /// Vanilla cached `BlockState.isSolid()` / `legacySolid`.
    #[serde(default)]
    l: Option<ScalarOrPerState>,
    /// Vanilla cached `BlockState.canBeReplaced()` property.
    #[serde(default)]
    v: Option<ScalarOrPerState>,
    /// Packed Direction ordinal bits for full-face sturdiness.
    #[serde(default)]
    t: Option<ScalarOrPerState>,
    /// Whether the generated logical collision/outline shape is translated by
    /// `BlockState.getOffset(pos)`. Legacy tables omit these fields and keep
    /// their historical unshifted compatibility shapes.
    #[serde(default)]
    co: Option<ScalarOrPerState>,
    #[serde(default)]
    oo: Option<ScalarOrPerState>,
    /// Generated `BlockBehaviour.OffsetType` and its clamp parameters.
    #[serde(default)]
    q: Option<ScalarOrPerState>,
    #[serde(default)]
    h: Option<ScalarOrPerStateF32>,
    #[serde(default)]
    y: Option<ScalarOrPerStateF32>,
    /// Collision and outline shape dictionary indices. Absent from older
    /// generated tables, which fall back to the native shape code below.
    #[serde(default)]
    s: Option<ScalarOrPerStateU32>,
    #[serde(default)]
    r: Option<ScalarOrPerStateU32>,
    #[serde(default)]
    f: Option<serde_json::Value>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum StateSemanticsMode {
    Generated,
    LegacyCompatibility,
}

fn state_semantics_mode(state_file: &StateFile) -> StateSemanticsMode {
    let mut mode = None;
    for entry in &state_file.blocks {
        let present = [
            entry.m.is_some(),
            entry.l.is_some(),
            entry.v.is_some(),
            entry.t.is_some(),
            entry.co.is_some(),
            entry.oo.is_some(),
            entry.q.is_some(),
            entry.h.is_some(),
            entry.y.is_some(),
            entry.s.is_some(),
            entry.r.is_some(),
        ];
        let entry_mode = if present.iter().all(|&value| value) {
            StateSemanticsMode::Generated
        } else if present.iter().all(|&value| !value) {
            StateSemanticsMode::LegacyCompatibility
        } else {
            panic!(
                "{}: generated block-state semantics/shape metadata is partial",
                entry.name
            );
        };
        if let Some(expected) = mode {
            assert_eq!(
                expected, entry_mode,
                "{}: state table mixes generated and legacy compatibility semantics",
                state_file.version
            );
        } else {
            mode = Some(entry_mode);
        }
    }
    let mode = mode.expect("state table must contain blocks");
    assert_eq!(
        !state_file.shapes.is_empty(),
        mode == StateSemanticsMode::Generated,
        "{}: shape dictionary does not match generated state metadata mode",
        state_file.version
    );
    mode
}

fn resolve_state_semantics(
    mode: StateSemanticsMode,
    entry: &StateEntry,
    offset: usize,
    collides: bool,
    is_air: bool,
) -> (bool, bool, bool, u8) {
    match mode {
        StateSemanticsMode::Generated => (
            entry
                .m
                .as_ref()
                .expect("generated blocksMotion")
                .get(offset)
                != 0,
            entry.l.as_ref().expect("generated legacySolid").get(offset) != 0,
            entry.v.as_ref().expect("generated replaceable").get(offset) != 0,
            entry
                .t
                .as_ref()
                .expect("generated full-face sturdy")
                .get(offset),
        ),
        StateSemanticsMode::LegacyCompatibility => {
            // Historical embedded state files predate these vanilla probes.
            // Keep their old runtime behavior explicitly, but do not present
            // these values as generated or authoritative for those versions.
            let blocks_motion = collides;
            let legacy_solid = blocks_motion;
            let replaceable = is_air;
            let full_face_sturdy = if collides { 0x3f } else { 0 };
            (blocks_motion, legacy_solid, replaceable, full_face_sturdy)
        }
    }
}

#[derive(serde::Deserialize)]
#[serde(untagged)]
enum ScalarOrPerState {
    One(u8),
    Many(Vec<u8>),
}

impl ScalarOrPerState {
    fn get(&self, offset: usize) -> u8 {
        match self {
            Self::One(v) => *v,
            Self::Many(vs) => vs[offset],
        }
    }
}

#[derive(serde::Deserialize)]
#[serde(untagged)]
enum ScalarOrPerStateF32 {
    One(f32),
    Many(Vec<f32>),
}

impl ScalarOrPerStateF32 {
    fn get(&self, offset: usize) -> f32 {
        match self {
            Self::One(v) => *v,
            Self::Many(vs) => vs[offset],
        }
    }
}

#[derive(serde::Deserialize)]
#[serde(untagged)]
enum ScalarOrPerStateU32 {
    One(u32),
    Many(Vec<u32>),
}

impl ScalarOrPerStateU32 {
    fn get(&self, offset: usize) -> u32 {
        match self {
            Self::One(v) => *v,
            Self::Many(vs) => vs[offset],
        }
    }
}

/// One version's embedded block tables. `blocks` is the state layout (ids and
/// properties from the data-generator report); `state` (`just stategen`)
/// holds the per-state values vanilla bakes at runtime, dumped by running its
/// own code.
struct EmbeddedBlocks {
    protocol: i32,
    blocks: &'static str,
    state: &'static str,
}

/// The `blocks-<v>.json` / `state-<v>.json` pair for version `v`, keyed by
/// its protocol (checked against the file in [`build_table`]).
macro_rules! embedded_blocks {
    ($protocol:expr, $version:literal) => {
        EmbeddedBlocks {
            protocol: $protocol,
            blocks: include_str!(concat!("data/blocks-", $version, ".json")),
            state: include_str!(concat!("data/state-", $version, ".json")),
        }
    };
}

