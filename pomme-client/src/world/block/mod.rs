/// Blocks the collision scan special-cases, tagged at table build so it
/// doesn't compare ids per cell.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum SpecialCollision {
    None,
    Scaffolding,
    PowderSnow,
    MovingPiston,
    ShulkerBox,
}

fn calculate_solid(collision: Option<&[LocalBox]>) -> bool {
    let Some(boxes) = collision else {
        return true;
    };
    let Some(&first) = boxes.first() else {
        return false;
    };
    let bounds = boxes.iter().fold(first, |mut b, bx| {
        for i in 0..3 {
            b[i] = b[i].min(bx[i]);
            b[i + 3] = b[i + 3].max(bx[i + 3]);
        }
        b
    });
    let [dx, dy, dz] = [0, 1, 2].map(|i| bounds[i + 3] - bounds[i]);
    (dx + dy + dz) / 3.0 >= 0.7291666666666666 || dy >= 1.0
}

#[derive(Clone, Copy)]
enum PositionOffsetKind {
    Xz,
    Xyz,
}

#[derive(Clone, Copy)]
struct PositionOffset {
    kind: PositionOffsetKind,
    max_horizontal: f32,
    max_vertical: f32,
    /// The offset at `BlockPos.ZERO`, which the generated shapes were dumped
    /// at.
    zero: DVec3,
}

impl PositionOffset {
    fn new(kind: PositionOffsetKind, max_horizontal: f32, max_vertical: f32) -> Self {
        let mut offset = Self {
            kind,
            max_horizontal,
            max_vertical,
            zero: DVec3::ZERO,
        };
        offset.zero = offset.at(0, 0);
        offset
    }

    /// Vanilla `BlockBehaviour.OffsetType` function for this column.
    fn at(&self, x: i32, z: i32) -> DVec3 {
        let seed = vanilla_position_seed(x, z);
        let raw_x = (f64::from((seed & 0xF) as f32 / 15.0_f32) - 0.5) * 0.5;
        let raw_z = (f64::from(((seed >> 8) & 0xF) as f32 / 15.0_f32) - 0.5) * 0.5;
        let max = f64::from(self.max_horizontal);
        let y = match self.kind {
            PositionOffsetKind::Xz => 0.0,
            PositionOffsetKind::Xyz => {
                (f64::from(((seed >> 4) & 0xF) as f32 / 15.0_f32) - 1.0)
                    * f64::from(self.max_vertical)
            }
        };
        dvec3(raw_x.clamp(-max, max), y, raw_z.clamp(-max, max))
    }
}

fn vanilla_position_seed(x: i32, z: i32) -> i64 {
    // Vanilla `Mth.getSeed(x, 0, z)`: the X multiplication is an i32
    // operation before widening, and the later products wrap signed 64-bit.
    let seed = i64::from(x.wrapping_mul(3_129_871)) ^ i64::from(z).wrapping_mul(116_129_781);
    seed.wrapping_mul(seed)
        .wrapping_mul(42_317_861)
        .wrapping_add(seed.wrapping_mul(11))
        >> 16
}

/// The generated shapes already hold ZERO's offset, so a position only adds
/// the difference to its own.
fn generated_shape_position_delta(block_state_data: &BlockStateData, x: i32, z: i32) -> DVec3 {
    block_state_data
        .position_offset
        .map_or(DVec3::ZERO, |offset| offset.at(x, z) - offset.zero)
}

fn shape_position(
    block_state_data: &BlockStateData,
    x: i32,
    y: i32,
    z: i32,
    uses_position_offset: bool,
) -> DVec3 {
    let origin = dvec3(x as f64, y as f64, z as f64);
    if uses_position_offset {
        origin + generated_shape_position_delta(block_state_data, x, z)
    } else {
        origin
    }
}

/// Vanilla `LightEngine.shapeOccludes(from, to, dir)` reduced to face masks:
/// whether `from`'s face and `to`'s opposite face together cover the full
/// face. `face` is the vanilla `Direction` ordinal (DOWN, UP, NORTH, SOUTH,
/// WEST, EAST); opposites pair as `face ^ 1`. Empty-shape states contribute
/// an empty mask, so two shapeless neighbors never occlude.
pub(crate) fn shape_occludes_data(
    from_block_state_data: &BlockStateData,
    to_block_state_data: &BlockStateData,
    face: usize,
) -> bool {
    let mask = |block_state_data: &BlockStateData, face: usize| {
        block_state_data
            .light
            .face_occlusion
            .map(|masks| &masks[face])
    };
    let a = mask(from_block_state_data, face);
    let b = mask(to_block_state_data, face ^ 1);
    if a.is_none() && b.is_none() {
        return false;
    }
    (0..16).all(|v| (a.map_or(0, |m| m[v]) | b.map_or(0, |m| m[v])) == 0xFFFF)
}

