/// Protocols whose block set is identical to a newer embedded version's (no
/// blocks added between them); they share that version's slot instead of
/// building a second copy of the same table. The slot also serves
/// `STATE_DATA`, so an alias requires the two versions' `generated/state.json`
/// dumps to be identical as well, not just the block list.
const SHARED_BLOCK_DATA: &[(i32, i32)] = &[
    // 1.21.7 added no blocks.
    (771, 772),
    // 1.21's trial-chamber blocks already existed in 1.20.6.
    (766, 767),
];

/// Per-state property tables (`just stategen`), index-aligned with
/// [`BLOCK_DATA`]. `blocks-<v>.json` is the state layout (ids and properties
/// from the data-generator report); `state-<v>.json` holds the per-state
/// values vanilla bakes at runtime, dumped by running its own code.
const STATE_DATA: [&str; BLOCK_DATA.len()] = [
    include_str!("data/state-26.2.json"),
    include_str!("data/state-26.1.json"),
    include_str!("data/state-1.21.11.json"),
    include_str!("data/state-1.21.10.json"),
    include_str!("data/state-1.21.8.json"),
    include_str!("data/state-1.21.5.json"),
    include_str!("data/state-1.21.4.json"),
    include_str!("data/state-1.21.3.json"),
    include_str!("data/state-1.21.1.json"),
    include_str!("data/state-1.20.4.json"),
    include_str!("data/state-1.20.2.json"),
];

/// One lazily-built table per embedded data file; `ACTIVE_TABLE` indexes the
/// protocol currently spoken (see [`set_active_protocol`]).
static BLOCK_TABLES: [OnceLock<Vec<BlockData>>; BLOCK_DATA.len()] =
    [const { OnceLock::new() }; BLOCK_DATA.len()];
static ACTIVE_TABLE: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);

/// Vanilla getFluidState overrides on blocks without a `waterlogged` property.
const IMPLICIT_WATER: [&str; 4] = ["seagrass", "tall_seagrass", "kelp", "kelp_plant"];

/// Loads the block-state table for the launched game version. Must be called
/// once at startup before any world/render code runs.
pub fn init(version: &str) {
    let protocol = pomme_protocol::ProtocolVersion::from_name(version)
        .map(|v| v.protocol)
        .unwrap_or_else(|| {
            tracing::warn!(
                "no block-state data for version {version}, using 26.2 — expect state drift"
            );
            pomme_protocol::version::LATEST.protocol
        });
    set_active_protocol(protocol);
}

/// Switches the active table to the given protocol's, building it on first
/// use, so state ids from the wire are interpreted natively in that
/// version's id space (no chunk remapping). Patch releases sharing a
/// protocol number (26.1 through 26.1.2 are all 775) get the same table.
/// Only safe between worlds — meshes built against the previous table
/// interpret ids in the old id space.
pub fn set_active_protocol(protocol: i32) {
    let slot = prewarm_protocol(protocol);
    ACTIVE_TABLE.store(slot, std::sync::atomic::Ordering::Release);
}

/// Builds the given protocol's table if it isn't already, without switching
/// to it; safe at any time (e.g. from a server-list ping, ahead of the join).
pub fn prewarm_protocol(protocol: i32) -> usize {
    let slot = block_data_slot(protocol).unwrap_or(0);
    BLOCK_TABLES[slot].get_or_init(|| build_table(BLOCK_DATA[slot].1, STATE_DATA[slot]));
    slot
}

/// The `BLOCK_DATA` slot serving a protocol, through `SHARED_BLOCK_DATA`.
fn block_data_slot(protocol: i32) -> Option<usize> {
    let protocol = SHARED_BLOCK_DATA
        .iter()
        .find(|&&(p, _)| p == protocol)
        .map_or(protocol, |&(_, shared)| shared);
    BLOCK_DATA.iter().position(|&(p, _)| p == protocol)
}

fn load_behaviors() -> HashMap<String, BehaviorEntry> {
    serde_json::from_str(include_str!("data/block_behavior.json"))
        .expect("invalid block-behavior data")
}

fn build_table(data: &str, state_data: &str) -> Vec<BlockData> {
    let file: BlockFile = serde_json::from_str(data).expect("invalid block-state data");
    let behaviors = load_behaviors();
    let state_file: StateFile = serde_json::from_str(state_data).expect("invalid state data");
    assert_eq!(
        state_file.version, file.version,
        "state data is for a different version"
    );
    assert_eq!(
        state_file.state_count, file.state_count,
        "state data state count mismatch"
    );
    assert_eq!(
        state_file.blocks.len(),
        file.blocks.len(),
        "state data block count mismatch"
    );
    let masks: &'static [FaceMask] = Vec::leak(
        state_file
            .masks
            .iter()
            .map(|hex| decode_face_mask(hex))
            .collect(),
    );
    // The same handful of 6-mask tuples repeats across thousands of states;
    // dedupe them into leaked statics so each state stores one pointer.
    let mut tuples: HashMap<[u32; 6], &'static [FaceMask; 6]> = HashMap::new();
    let mut tuple = |indices: [u32; 6]| -> &'static [FaceMask; 6] {
        tuples
            .entry(indices)
            .or_insert_with(|| Box::leak(Box::new(indices.map(|i| masks[i as usize]))))
    };

    let mut interner: HashSet<&'static str> = HashSet::new();
    let mut intern = |s: &str| -> &'static str {
        match interner.get(s) {
            Some(&e) => e,
            None => {
                let leaked: &'static str = Box::leak(s.to_string().into_boxed_str());
                interner.insert(leaked);
                leaked
            }
        }
    };

    let mut table: Vec<BlockData> = Vec::with_capacity(file.state_count as usize);
    for (block, state_entry) in file.blocks.iter().zip(&state_file.blocks) {
        assert_eq!(
            block.first_id,
            table.len() as u32,
            "block-state data not dense at '{}'",
            block.name
        );
        assert_eq!(
            state_entry.name, block.name,
            "state data out of order at '{}'",
            block.name
        );
        let name = intern(&block.name);
        let behavior = match behaviors.get(&block.name) {
            Some(b) => BlockBehavior {
                destroy_time: b.destroy_time,
                requires_correct_tool_for_drops: b.requires_correct_tool,
            },
            None => {
                tracing::warn!("no behavior entry for block '{}', using defaults", name);
                DEFAULT_BEHAVIOR
            }
        };
        let props: Vec<(&'static str, Vec<&'static str>)> = block
            .props
            .iter()
            .map(|(k, vs)| (intern(k), vs.iter().map(|v| intern(v)).collect()))
            .collect();
        let is_air = matches!(block.name.as_str(), "air" | "cave_air" | "void_air");
        let collides = state_entry.c != 0;

        let count: u32 = props.iter().map(|(_, vs)| vs.len() as u32).product();
        let face_indices = light_face_indices(state_entry, count as usize);
        for offset in 0..count {
            let mut pairs = Vec::with_capacity(props.len());
            let mut stride = count;
            for (key, values) in &props {
                stride /= values.len() as u32;
                pairs.push((*key, values[(offset / stride) as usize % values.len()]));
            }
            let properties = PropMap::from_pairs(pairs);
            let fluid = state_fluid(name, &properties);
            let shape = compute_shape(name, &properties).map(Vec::into_boxed_slice);
            let outline = compute_outline(name, &properties).map(Vec::into_boxed_slice);
            let light = LightProps {
                emission: state_entry.e.get(offset as usize),
                dampening: state_entry.d.get(offset as usize),
                propagates_skylight_down: state_entry.p.get(offset as usize) != 0,
                can_occlude: state_entry.o.get(offset as usize) != 0,
                use_shape_for_light_occlusion: state_entry.u.get(offset as usize) != 0,
                face_occlusion: face_indices[offset as usize].map(&mut tuple),
            };
            table.push(BlockData {
                id: name,
                properties,
                behavior,
                shape,
                outline,
                is_air,
                collides,
                fluid,
                light,
            });
        }
    }

    assert_eq!(
        table.len() as u32,
        file.state_count,
        "block-state data table size mismatch for {}",
        file.version
    );
    table
}

fn decode_face_mask(hex: &str) -> FaceMask {
    assert_eq!(hex.len(), 64, "face mask must be 64 hex chars");
    std::array::from_fn(|v| {
        u16::from_str_radix(&hex[v * 4..v * 4 + 4], 16).expect("invalid face-mask hex")
    })
}

/// Expands a light entry's `f` field into per-state mask-dictionary tuples.
fn light_face_indices(entry: &StateEntry, count: usize) -> Vec<Option<[u32; 6]>> {
    let Some(f) = &entry.f else {
        return vec![None; count];
    };
    let arr = f
        .as_array()
        .unwrap_or_else(|| panic!("{}: face-mask field is not an array", entry.name));
    let parse_tuple = |values: &[serde_json::Value]| -> [u32; 6] {
        assert_eq!(values.len(), 6, "{}: face-mask tuple length", entry.name);
        std::array::from_fn(|i| {
            values[i]
                .as_u64()
                .unwrap_or_else(|| panic!("{}: non-numeric face-mask index", entry.name))
                as u32
        })
    };
    if arr.first().is_some_and(serde_json::Value::is_number) {
        // Uniform across the block: a single 6-index tuple.
        return vec![Some(parse_tuple(arr)); count];
    }
    assert_eq!(arr.len(), count, "{}: face-mask entry count", entry.name);
    arr.iter()
        .map(|v| {
            if v.is_null() {
                None
            } else {
                Some(parse_tuple(v.as_array().unwrap_or_else(|| {
                    panic!("{}: face-mask entry is not a tuple", entry.name)
                })))
            }
        })
        .collect()
}

fn state_fluid(name: &'static str, props: &PropMap) -> Fluid {
    match name {
        "water" | "lava" => {
            let level: u8 = props.get("level").and_then(|l| l.parse().ok()).unwrap_or(0);
            let kind = if name == "water" {
                FluidKind::Water
            } else {
                FluidKind::Lava
            };
            if level >= 8 {
                Fluid {
                    kind,
                    amount: 8,
                    falling: true,
                }
            } else {
                Fluid {
                    kind,
                    amount: 8 - level,
                    falling: false,
                }
            }
        }
        "bubble_column" => FULL_WATER,
        _ if IMPLICIT_WATER.contains(&name) => FULL_WATER,
        _ if props.get("waterlogged") == Some("true") => FULL_WATER,
        _ => NO_FLUID,
    }
}

fn table() -> &'static Vec<BlockData> {
    BLOCK_TABLES[ACTIVE_TABLE.load(std::sync::atomic::Ordering::Acquire)]
        .get()
        .expect("world::block::init must be called before use")
}

fn block_data(state: BlockState) -> &'static BlockData {
    static UNKNOWN: std::sync::LazyLock<BlockData> = std::sync::LazyLock::new(|| BlockData {
        id: "unknown",
        properties: PropMap::from_pairs(Vec::new()),
        behavior: DEFAULT_BEHAVIOR,
        shape: None,
        outline: None,
        is_air: false,
        collides: true,
        fluid: NO_FLUID,
        light: BEDROCK_LIGHT,
    });
    table().get(u32::from(state) as usize).unwrap_or(&UNKNOWN)
}

/// Every valid block state paired with its cached data, in id order.
fn all_states() -> impl Iterator<Item = (BlockState, &'static BlockData)> {
    table().iter().enumerate().map(|(id, data)| {
        let state = BlockState::try_from(id as u32).expect("table indices fit the id repr");
        (state, data)
    })
}

/// First declared state of the named block, e.g. the light engine's bedrock
/// fallback for unloaded-chunk reads.
pub(crate) fn first_state_of(name: &str) -> Option<BlockState> {
    all_states().find(|(_, d)| d.id == name).map(|(s, _)| s)
}

/// Converts a wire-side numeric state id, validated against the loaded table.
pub fn try_state(id: u32) -> Option<BlockState> {
    if (id as usize) < table().len() {
        BlockState::try_from(id).ok()
    } else {
        None
    }
}

pub fn block_id(state: BlockState) -> &'static str {
    block_data(state).id
}

pub fn block_properties(state: BlockState) -> &'static PropMap {
    &block_data(state).properties
}

pub fn block_behavior(state: BlockState) -> &'static BlockBehavior {
    &block_data(state).behavior
}

/// Vanilla `RedStoneWireBlock.getColorForPower`: dust tint for the state's
/// `power` value.
pub fn redstone_wire_rgb(state: BlockState) -> [f32; 3] {
    static COLORS: std::sync::LazyLock<[[f32; 3]; 16]> = std::sync::LazyLock::new(|| {
        std::array::from_fn(|power| {
            let f = power as f32 / 15.0;
            let red = f * 0.6 + if power > 0 { 0.4 } else { 0.3 };
            let green = (f * f * 0.7 - 0.5).clamp(0.0, 1.0);
            let blue = (f * f * 0.6 - 0.7).clamp(0.0, 1.0);
            [red, green, blue]
        })
    });
    let power: usize = block_properties(state)
        .get("power")
        .and_then(|p| p.parse().ok())
        .unwrap_or(0);
    COLORS[power.min(15)]
}

/// Vanilla `isAir`: includes cave and void air.
pub fn is_air(state: BlockState) -> bool {
    block_data(state).is_air
}

/// Whether the state's block collides with entities (vanilla `hasCollision`).
pub fn has_collision(state: BlockState) -> bool {
    block_data(state).collides
}

pub fn fluid(state: BlockState) -> Fluid {
    block_data(state).fluid
}

pub(crate) fn block_shape(state: BlockState) -> Option<&'static [LocalBox]> {
    block_data(state).shape.as_deref()
}

/// Outline shape for interaction raycasts (vanilla `getShape`), falling back to
/// the collision shape where the two agree. `None` is a full cube; an empty
/// slice is a block the pick ray passes through.
pub(crate) fn block_outline(state: BlockState) -> Option<&'static [LocalBox]> {
    let data = block_data(state);
    data.outline.as_deref().or(data.shape.as_deref())
}

/// Baked light properties for a state (vanilla `BlockStateBase` light cache).
pub fn light_props(state: BlockState) -> LightProps {
    block_data(state).light
}

/// Vanilla `LightEngine.isEmptyShape`: the state needs no voxel-shape
/// occlusion tests (full opaque cubes qualify — their opacity handles them).
pub fn is_empty_shape(state: BlockState) -> bool {
    let light = block_data(state).light;
    !light.can_occlude || !light.use_shape_for_light_occlusion
}

/// Vanilla `LightEngine.shapeOccludes(from, to, dir)` reduced to face masks:
/// whether `from`'s face and `to`'s opposite face together cover the full
/// face. `face` is the vanilla `Direction` ordinal (DOWN, UP, NORTH, SOUTH,
/// WEST, EAST); opposites pair as `face ^ 1`. Empty-shape states contribute
/// an empty mask, so two shapeless neighbors never occlude.
pub fn shape_occludes(from: BlockState, to: BlockState, face: usize) -> bool {
    let mask = |state: BlockState, face: usize| {
        block_data(state)
            .light
            .face_occlusion
            .map(|masks| &masks[face])
    };
    let a = mask(from, face);
    let b = mask(to, face ^ 1);
    if a.is_none() && b.is_none() {
        return false;
    }
    (0..16).all(|v| (a.map_or(0, |m| m[v]) | b.map_or(0, |m| m[v])) == 0xFFFF)
}

/// The block's state matching the given property values (unlisted properties
/// take whatever the first match has); shared with the light-engine tests.
#[cfg(test)]
pub(crate) fn find_state(name: &str, props: &[(&str, &str)]) -> BlockState {
    all_states()
        .find(|(s, d)| {
            d.id == name
                && props
                    .iter()
                    .all(|&(k, v)| block_properties(*s).get(k) == Some(v))
        })
        .unwrap_or_else(|| panic!("no state {name} {props:?}"))
        .0
}

