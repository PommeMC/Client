#[derive(serde::Deserialize)]
struct StateFile {
    version: String,
    state_count: u32,
    /// Deduped face masks as 64-hex-char strings (16 rows of 4 chars).
    masks: Vec<String>,
    /// Deduped exact vanilla collision/outline shapes. Older generated tables
    /// omit this field and continue using the hand-computed fallback.
    #[serde(default)]
    shapes: Vec<Vec<f64>>,
    blocks: Vec<StateEntry>,
}

/// Per-block fields; each is a scalar when uniform across the block's
/// states, else one value per state. `f` is 6 mask-dictionary indices —
/// a single tuple when uniform, else a per-state list of tuple-or-null.
#[derive(serde::Deserialize)]
struct StateEntry {
    name: String,
    e: PerState<u8>,
    d: PerState<u8>,
    p: PerState<u8>,
    o: PerState<u8>,
    u: PerState<u8>,
    /// `hasCollision`; block-level in vanilla, so always a scalar.
    c: u8,
    /// `blocksMotion` (absent from 26.3 on), `isSolid`, `canBeReplaced` and
    /// full-face sturdy bits.
    #[serde(default)]
    m: Option<PerState<u8>>,
    #[serde(default)]
    l: Option<PerState<u8>>,
    #[serde(default)]
    v: Option<PerState<u8>>,
    #[serde(default)]
    t: Option<PerState<u8>>,
    /// Whether the collision/outline shape follows `getOffset(pos)`.
    #[serde(default)]
    co: Option<PerState<u8>>,
    #[serde(default)]
    oo: Option<PerState<u8>>,
    /// `BlockBehaviour.OffsetType` (0 none, 1 XZ, 2 XYZ) and its clamps.
    #[serde(default)]
    q: Option<PerState<u8>>,
    #[serde(default)]
    h: Option<PerState<f32>>,
    #[serde(default)]
    y: Option<PerState<f32>>,
    /// Collision and outline shape dictionary indices.
    #[serde(default)]
    s: Option<PerState<u32>>,
    #[serde(default)]
    r: Option<PerState<u32>>,
    #[serde(default)]
    f: Option<serde_json::Value>,
}

/// The generated shape and offset fields of a [`StateEntry`].
struct GeneratedShapeFields<'a> {
    collision_offset: &'a PerState<u8>,
    outline_offset: &'a PerState<u8>,
    offset_type: &'a PerState<u8>,
    max_horizontal: &'a PerState<f32>,
    max_vertical: &'a PerState<f32>,
    collision: &'a PerState<u32>,
    outline: &'a PerState<u32>,
}

impl StateEntry {
    fn generated_shapes(&self) -> GeneratedShapeFields<'_> {
        match (
            &self.co, &self.oo, &self.q, &self.h, &self.y, &self.s, &self.r,
        ) {
            (Some(co), Some(oo), Some(q), Some(h), Some(y), Some(s), Some(r)) => {
                GeneratedShapeFields {
                    collision_offset: co,
                    outline_offset: oo,
                    offset_type: q,
                    max_horizontal: h,
                    max_vertical: y,
                    collision: s,
                    outline: r,
                }
            }
            _ => panic!(
                "{}: missing generated shape fields; run `just stategen`",
                self.name
            ),
        }
    }
}

/// A scalar when uniform across the block's states, else one value per state.
#[derive(serde::Deserialize)]
#[serde(untagged)]
enum PerState<T> {
    One(T),
    Many(Vec<T>),
}

impl<T: Copy> PerState<T> {
    fn get(&self, offset: usize) -> T {
        match self {
            Self::One(v) => *v,
            Self::Many(vs) => vs[offset],
        }
    }
}

/// One version's embedded block tables. `blocks` is the state layout (ids and
/// properties from the data-generator report); `state` (`just stategen`)
/// holds the per-state values vanilla bakes at runtime, dumped by running its
/// own code.
struct EmbeddedBlocks {
    protocol: i32,
    /// Deflated by `build.rs` (see [`embedded_data`]); read through
    /// [`parse_embedded`].
    blocks: &'static [u8],
    state: &'static [u8],
    piston: &'static [u8],
}

/// Inflates one of an [`EmbeddedBlocks`]' tables and parses it.
fn parse_embedded<T: serde::de::DeserializeOwned>(deflated: &[u8]) -> T {
    use std::io::Read;

    let mut json = Vec::new();
    flate2::read::DeflateDecoder::new(deflated)
        .read_to_end(&mut json)
        .expect("embedded block data inflates");
    serde_json::from_slice(&json).expect("embedded block data parses")
}

/// The deflated copy of `data/<name>` that `build.rs` writes.
macro_rules! embedded_data {
    ($($name:expr),+) => {
        include_bytes!(concat!(env!("OUT_DIR"), "/block-data/", $($name),+))
    };
}

/// The `blocks-<v>.json`, `state-<v>.json` and `piston-<v>.json` tables for
/// version `v`, keyed by its protocol (checked against the file in
/// [`build_table`]).
macro_rules! embedded_blocks {
    ($protocol:expr, $version:literal) => {
        EmbeddedBlocks {
            protocol: $protocol,
            blocks: embedded_data!("blocks-", $version, ".json"),
            state: embedded_data!("state-", $version, ".json"),
            piston: embedded_data!("piston-", $version, ".json"),
        }
    };
}

