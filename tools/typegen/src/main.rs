//! Generates pomme-registry's entry lists and tags from a reference
//! version's data-generator output.
//!
//! Usage:
//!   typegen <reference-root> <version> <pomme-registry/src>
//!   e.g. typegen reference/26.2 26.2 pomme-registry/src
//!
//! Writes, as invocations of the crate's own macros:
//! - `builtin.rs`: every builtin registry in protocol-id order, from
//!   `generated/reports/registries.json`
//! - `data/generated.rs`: the keys of the registries a server sends, from the
//!   folders of `extracted/data/minecraft` (and `worldgen/biome`)
//! - `tags/{blocks,items,fluids,entities}.rs`: the data pack's tags, each
//!   flattened and in protocol-id order
//!
//! Run `cargo fmt -p pomme-registry` afterwards (`just typegen` does). It
//! hard-fails on anything it can't resolve rather than emit wrong data.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use serde_json::Value;

type Error = Box<dyn std::error::Error>;

/// The tagged registries and each one's module in `tags/`.
const TAGGED: [(&str, &str); 4] = [
    ("block", "blocks"),
    ("item", "items"),
    ("fluid", "fluids"),
    ("entity_type", "entities"),
];

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [reference, version, out] = args.as_slice() else {
        eprintln!("usage: typegen <reference-root> <version> <pomme-registry/src>");
        return ExitCode::FAILURE;
    };
    match generate(Path::new(reference), version, Path::new(out)) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("typegen: {e}");
            ExitCode::FAILURE
        }
    }
}

fn generate(reference: &Path, version: &str, out: &Path) -> Result<(), Error> {
    let report = reference.join("generated/reports/registries.json");
    let registries = builtin_registries(&read_json(&report)?)?;
    let data = reference.join("extracted/data/minecraft");
    let header =
        format!("// @generated by `just typegen {version}` (tools/typegen). Do not edit.\n");

    let mut builtin = header.clone();
    for (name, entries) in &registries {
        writeln!(builtin, "\nregistry!({} {{", enum_name(name))?;
        for entry in entries {
            writeln!(builtin, "    {} => \"{entry}\",", variant(entry))?;
        }
        builtin.push_str("});\n");
    }
    write(&out.join("builtin.rs"), &builtin)?;

    let mut keys = header.clone();
    for (name, entries) in data_registries(&data)? {
        let registry = enum_name(name.rsplit('/').next().unwrap_or(&name));
        writeln!(
            keys,
            "\ndata_registry!({registry}, \"{name}\", {registry}Key {{"
        )?;
        for entry in entries {
            writeln!(keys, "    {} => \"{entry}\",", variant(&entry))?;
        }
        keys.push_str("});\n");
    }
    write(&out.join("data/generated.rs"), &keys)?;

    for (registry, module) in TAGGED {
        let entries = registries
            .get(registry)
            .ok_or_else(|| format!("no {registry} registry in {}", report.display()))?;
        let tags = tags(&data.join("tags").join(registry), entries)?;
        let kind = enum_name(registry);
        let mut code =
            format!("{header}\nuse crate::builtin::{kind};\nuse crate::tags::RegistryTag;\n");
        for (name, ids) in tags {
            let listed: Vec<String> = ids
                .iter()
                .map(|&id| format!("{kind}::{}", variant(&entries[id])))
                .collect();
            writeln!(
                code,
                "\npub static {}: RegistryTag<{kind}> = RegistryTag::new(&[{}]);",
                static_name(&name),
                listed.join(", ")
            )?;
        }
        write(&out.join("tags").join(format!("{module}.rs")), &code)?;
    }
    Ok(())
}

/// Leads an error with the path it came from.
fn at<E: std::fmt::Display>(path: &Path) -> impl Fn(E) -> String + '_ {
    move |e| format!("{}: {e}", path.display())
}

fn read_json(path: &Path) -> Result<Value, Error> {
    let text = std::fs::read_to_string(path).map_err(at(path))?;
    Ok(serde_json::from_str(&text).map_err(at(path))?)
}

fn write(path: &Path, text: &str) -> Result<(), Error> {
    Ok(std::fs::write(path, text).map_err(at(path))?)
}

/// What `dir` holds, each by its name without an extension, in name order.
fn children(dir: &Path) -> Result<Vec<(String, PathBuf)>, Error> {
    let mut children = Vec::new();
    for entry in std::fs::read_dir(dir).map_err(at(dir))? {
        let path = entry.map_err(at(dir))?.path();
        let stem = path.file_stem().and_then(|s| s.to_str());
        let stem = stem.ok_or_else(|| format!("{}: not UTF-8", path.display()))?;
        children.push((stem.to_owned(), path));
    }
    children.sort();
    Ok(children)
}

fn is_json(path: &Path) -> bool {
    path.extension().is_some_and(|ext| ext == "json")
}

/// An identifier's path; only the game's own namespaces are expected.
fn path_of(ident: &str) -> Result<&str, Error> {
    match ident.split_once(':') {
        None => Ok(ident),
        Some(("minecraft" | "brigadier", path)) => Ok(path),
        Some(_) => Err(format!("{ident} is outside the game's namespaces").into()),
    }
}

/// Each builtin registry's entry paths in protocol-id order, by its path.
fn builtin_registries(report: &Value) -> Result<BTreeMap<String, Vec<String>>, Error> {
    let report = report
        .as_object()
        .ok_or("the registries report isn't an object")?;
    let mut registries = BTreeMap::new();
    for (name, registry) in report {
        let entries = registry["entries"]
            .as_object()
            .ok_or_else(|| format!("{name} has no entries"))?;
        let mut ordered = vec![None; entries.len()];
        for (entry, data) in entries {
            let id = data["protocol_id"]
                .as_u64()
                .ok_or_else(|| format!("{name} {entry} has no protocol id"))?;
            let slot = ordered
                .get_mut(id as usize)
                .ok_or_else(|| format!("{name} {entry} has id {id} past the registry's end"))?;
            if slot.replace(path_of(entry)?.to_owned()).is_some() {
                return Err(format!("{name} has two entries with id {id}").into());
            }
        }
        // Every slot is filled: as many distinct ids as entries, all in range.
        let ordered = ordered.into_iter().flatten().collect();
        registries.insert(path_of(name)?.to_owned(), ordered);
    }
    Ok(registries)
}

/// The `.json` files directly in `dir`, by name without the extension.
fn json_stems(dir: &Path) -> Result<Vec<String>, Error> {
    let files = children(dir)?.into_iter().filter(|(_, path)| is_json(path));
    Ok(files.map(|(stem, _)| stem).collect())
}

/// The data pack's registries and their entries: each folder holding entry
/// files directly, and `worldgen` only for its biomes.
fn data_registries(data: &Path) -> Result<BTreeMap<String, Vec<String>>, Error> {
    let mut registries = BTreeMap::new();
    for (name, path) in children(data)? {
        if path.is_dir() {
            registries.insert(name, json_stems(&path)?);
        }
    }
    registries.insert(
        "worldgen/biome".to_owned(),
        json_stems(&data.join("worldgen/biome"))?,
    );
    registries.retain(|_, entries| !entries.is_empty());
    Ok(registries)
}

/// Every tag under `dir` by its path (`mineable/axe`), as the ids of its
/// entries in ascending order, with the tags it names flattened in.
fn tags(dir: &Path, entries: &[String]) -> Result<BTreeMap<String, Vec<usize>>, Error> {
    let mut values = BTreeMap::new();
    collect_tags(dir, "", &mut values)?;
    let mut tags = BTreeMap::new();
    for name in values.keys() {
        let mut ids = Vec::new();
        let mut pending = vec![name.as_str()];
        // A tag naming itself, even through others, would never end.
        let mut visited = vec![name.as_str()];
        while let Some(tag) = pending.pop() {
            for value in &values[tag] {
                if let Some(nested) = value.strip_prefix('#') {
                    let nested = path_of(nested)?;
                    let (nested, _) = values
                        .get_key_value(nested)
                        .ok_or_else(|| format!("tag {name} names the missing tag {nested}"))?;
                    if !visited.contains(&nested.as_str()) {
                        visited.push(nested);
                        pending.push(nested);
                    }
                } else {
                    let entry = path_of(value)?;
                    let id = entries.iter().position(|e| e == entry);
                    ids.push(id.ok_or_else(|| format!("tag {name} names the missing {entry}"))?);
                }
            }
        }
        ids.sort_unstable();
        ids.dedup();
        tags.insert(name.clone(), ids);
    }
    Ok(tags)
}

/// Reads the tag files under `dir` into `values`, keyed by path below the
/// tags folder.
fn collect_tags(
    dir: &Path,
    prefix: &str,
    values: &mut BTreeMap<String, Vec<String>>,
) -> Result<(), Error> {
    for (stem, path) in children(dir)? {
        let name = format!("{prefix}{stem}");
        if path.is_dir() {
            collect_tags(&path, &format!("{name}/"), values)?;
        } else if is_json(&path) {
            let listed = read_json(&path)?["values"]
                .as_array()
                .ok_or_else(|| format!("{} has no values", path.display()))?
                .iter()
                .map(|v| {
                    v.as_str()
                        .map(str::to_owned)
                        .ok_or("a tag value that isn't a string")
                })
                .collect::<Result<_, _>>()?;
            values.insert(name, listed);
        }
    }
    Ok(())
}

/// A registry's Rust type name: `_type` reads as `Kind`, and the registries
/// whose bare name would be too plain a type name get it too.
fn enum_name(registry: &str) -> String {
    let name = match registry {
        // `BlockKind` is the block registry.
        "block_type" => "abstract_block_kind".to_owned(),
        "menu" | "block" | "item" | "banner_pattern" => format!("{registry}_kind"),
        _ => match registry.strip_suffix("_type") {
            Some(stem) => format!("{stem}_kind"),
            None => registry.to_owned(),
        },
    };
    variant(&name)
}

/// A path as a Rust variant name: `oak_log` is `OakLog`, `11` is `_11`.
fn variant(path: &str) -> String {
    let mut name = String::with_capacity(path.len() + 1);
    let mut upper = true;
    for c in path.chars() {
        match c {
            '_' | '.' | '/' | ' ' => upper = true,
            c if upper => {
                name.extend(c.to_uppercase());
                upper = false;
            }
            c => name.push(c),
        }
    }
    if name.starts_with(|c: char| c.is_ascii_digit()) {
        name.insert(0, '_');
    }
    name
}

/// A tag's path as a static's name: `mineable/axe` is `MINEABLE_AXE`.
fn static_name(tag: &str) -> String {
    tag.replace(['/', '.'], "_").to_uppercase()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_follow_the_registry_paths() {
        assert_eq!(variant("oak_log"), "OakLog");
        assert_eq!(variant("11"), "_11");
        assert_eq!(variant("entity.cushion.sit"), "EntityCushionSit");
        assert_eq!(enum_name("item"), "ItemKind");
        assert_eq!(enum_name("entity_type"), "EntityKind");
        assert_eq!(enum_name("block_type"), "AbstractBlockKind");
        assert_eq!(enum_name("sound_event"), "SoundEvent");
        assert_eq!(static_name("mineable/axe"), "MINEABLE_AXE");
    }

    #[test]
    fn registries_are_ordered_by_protocol_id() {
        let report = serde_json::json!({
            "minecraft:item": {"entries": {
                "minecraft:stone": {"protocol_id": 1},
                "minecraft:air": {"protocol_id": 0},
            }},
        });
        let registries = builtin_registries(&report).unwrap();
        assert_eq!(registries["item"], ["air", "stone"]);

        let clash = serde_json::json!({
            "minecraft:item": {"entries": {
                "minecraft:stone": {"protocol_id": 0},
                "minecraft:air": {"protocol_id": 0},
            }},
        });
        assert!(builtin_registries(&clash).is_err());
        assert!(path_of("mod:thing").is_err());
    }
}
