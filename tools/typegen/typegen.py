#!/usr/bin/env python3
"""Regenerates pomme-registry's tables and pomme-inventory's default
components from a reference version's data-generator output.

    python tools/typegen/typegen.py reference/<version>

Reads `generated/reports/registries.json`, the item component reports under
`generated/reports/minecraft/components/item/`, and the data pack under
`extracted/data/minecraft/`. Run `cargo fmt -p azalea-registry -p
azalea-inventory` afterwards (`just typegen` does).

Ported from azalea's codegen (`codegen/lib/code/{registry,tags,
data_components}.py`, MIT, Copyright (c) 2022 mat), which the two crates were
generated by before they were forked.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BUILTIN = ROOT / "pomme-registry/src/builtin.rs"
DATA = ROOT / "pomme-registry/src/data.rs"
TAGS = ROOT / "pomme-registry/src/tags"
MENUS = ROOT / "pomme-inventory/src/lib.rs"
COMPONENTS = ROOT / "pomme-inventory/src/components/mod.rs"
DEFAULT_COMPONENTS = ROOT / "pomme-inventory/src/default_components/generated.rs"

GENERATED = "// This file was @generated by tools/typegen/typegen.py, don't edit it manually!\n"
# The tagged registries and each one's module in `tags/`.
TAGGED = {"block": "blocks", "item": "items", "fluid": "fluids", "entity_type": "entities"}
NUMBERS = {"i64", "u64", "f64", "i32", "u32", "f32", "i16", "u16", "i8", "u8"}
# A component held in a per-item table rather than a match past this many items.
TABLE_THRESHOLD = 128


def write(path, text):
    path.write_text(text, encoding="utf-8", newline="\n")


def to_snake_case(name):
    s = re.sub("([A-Z])", r"_\1", name).replace(".", "_").replace("/", "_")
    return s.lower().strip("_")


def to_camel_case(name):
    s = re.sub(r"[_ ](\w)", lambda m: m.group(1).upper(), name.replace(".", "_").replace("/", "_"))
    s = s[0].upper() + s[1:]
    return f"_{s}" if s[0].isdigit() else s


def path_of(ident):
    """An identifier without its namespace, or `<namespace>_<path>` for a
    namespace that isn't the game's."""
    if ":" not in ident:
        return ident
    namespace, path = ident.lstrip("#").split(":")
    return path if namespace in {"minecraft", "brigadier"} else f"{namespace}_{path}"


def variant(ident):
    return to_camel_case(path_of(ident))


def enum_name(registry):
    registry = path_of(registry)
    if registry == "block_type":
        # `BlockKind` is the block registry.
        registry = "abstract_block_kind"
    elif registry.endswith("_type"):
        registry = registry[:-5] + "_kind"
    elif registry in {"menu", "block", "item", "banner_pattern"}:
        registry += "_kind"
    return to_camel_case(registry)


def by_protocol_id(registry):
    return [name for name, _ in sorted(registry["entries"].items(), key=lambda e: e[1]["protocol_id"])]


def variants(registry):
    return [variant(name) for name in by_protocol_id(registry)]


def json_tree(directory):
    """Every JSON file under `directory`, keyed by its path without `.json`."""
    return {file.relative_to(directory).with_suffix("").as_posix(): json.loads(file.read_text())
            for file in sorted(directory.rglob("*.json"))}


def replace_blocks(path, macro, blocks):
    """Rewrites the `<macro>! { ... }` blocks of `path`. `blocks` maps each
    block's enum line to what a new block opens with and its variant lines.
    A block whose enum isn't in `blocks` is deleted, a new one is appended,
    and what an existing one holds ahead of its enum (doc comments, a data
    registry's name) is kept."""
    code = path.read_text().split("\n")
    opener = f"{macro}! {{"
    out, seen, i = [], set(), 0
    while i < len(code):
        if code[i] != opener:
            out.append(code[i])
            i += 1
            continue
        # The enum's closing brace, then the macro's.
        end = code.index("}", code.index("}", i) + 1)
        enum_at = next(n for n in range(i, end) if code[n].startswith("enum "))
        if code[enum_at] in blocks:
            seen.add(code[enum_at])
            out += [*code[i:enum_at + 1], *blocks[code[enum_at]][1], "}", "}"]
        elif end + 1 < len(code) and code[end + 1] == "":
            end += 1
        i = end + 1
    for enum_line, (head, entries) in blocks.items():
        if enum_line not in seen:
            out += [opener, *head, enum_line, *entries, "}", "}", ""]
    write(path, "\n".join(out))


def generate_builtin(registries):
    blocks = {}
    for name, registry in registries.items():
        entries = [f'    {variant(v)} => "{path_of(v)}",' for v in by_protocol_id(registry)]
        blocks[f"enum {enum_name(name)} {{"] = ([], entries)
    replace_blocks(BUILTIN, "registry", blocks)


def generate_data(data_registries):
    blocks = {}
    for name, entries in data_registries.items():
        struct = enum_name(name.split("/")[-1])
        keys = [f'    {variant(v)} => "{v}",' for v in sorted(entries)]
        blocks[f"enum {struct}Key {{"] = ([f'{struct} => "{name}",'], keys)
    replace_blocks(DATA, "data_registry", blocks)


def data_registries(data):
    """The data pack's registries and their entries; `worldgen` only for its
    biomes."""
    found = {}
    for directory in [*sorted(data.iterdir()), data / "worldgen" / "biome"]:
        entries = [file.stem for file in directory.glob("*.json")] if directory.is_dir() else []
        if entries:
            found[directory.relative_to(data).as_posix()] = entries
    return found


def generate_tags(registries, tags, module, registry):
    kind = enum_name(registry)
    protocol_ids = {path_of(n): i for i, n in enumerate(by_protocol_id(registries[f"minecraft:{registry}"]))}
    code = f"{GENERATED}\nuse std::sync::LazyLock;\n\nuse crate::{{builtin::{kind}, tags::RegistryTag}};\n\n"
    for name, tag in sorted(tags.items()):
        entries, queue = [], list(tag["values"])
        while queue:
            ident = queue.pop(0)
            if ident.startswith("#"):
                queue += tags[path_of(ident)]["values"]
            else:
                entries.append(path_of(ident))
        # Tags are binary searched, so they hold their entries in id order.
        entries.sort(key=lambda e: protocol_ids[e])
        # Mojang's spelling.
        static = to_snake_case(name.replace("/", "_")).upper().replace("CONVERTABLE", "CONVERTIBLE")
        listed = "".join(f"{kind}::{to_camel_case(e)},\n" for e in entries)
        code += f"pub static {static}: LazyLock<RegistryTag<{kind}>> = LazyLock::new(|| RegistryTag::new(vec![{listed}]));\n"
    write(TAGS / f"{module}.rs", code)


def check_menus(registries):
    """The menus `declare_menus!` lists are hand-written; says which to add
    or remove when the registry's changed."""
    expected = ["Player", *variants(registries["minecraft:menu"])]
    lines = MENUS.read_text().split("\n")
    start = next(i for i, line in enumerate(lines) if line.startswith("declare_menus!"))
    declared = [line[:-1].strip() for line in lines[start:] if line.startswith("    ") and line.endswith("{")
                and not line.startswith("     ")]
    if declared != expected:
        sys.exit(f"typegen: declare_menus! in {MENUS} lists {declared}, the registry has {expected}")


def check_components(registries):
    """The component structs are hand-written; says which to add or remove
    when the registry's changed."""
    expected = variants(registries["minecraft:data_component_type"])
    declared, inside = [], False
    for line in COMPONENTS.read_text().split("\n"):
        if line == "define_data_components!(":
            inside = True
        elif inside and line == ");":
            break
        elif inside and line.startswith("    ") and line.strip()[0] not in "#/":
            declared.append(line.strip(" ,").split()[0])
    added = [c for c in expected if c not in declared]
    removed = [c for c in declared if c not in expected]
    if added or removed:
        sys.exit(f"typegen: define_data_components! in {COMPONENTS} is out of date: add {added}, remove {removed}")


def declared_types():
    """Each struct's `{field: type}` and each enum's variant list in the
    components module."""
    code = COMPONENTS.read_text().split("\n")
    found = {}
    for i, line in enumerate(code):
        if not line.startswith(("pub struct ", "pub enum ")):
            continue
        # Empty for a declaration that closes on its own line.
        body = [] if line[-1] in "};" else [b.strip() for b in code[i + 1:code.index("}", i)]]
        name = line.split()[2].strip(":;")
        if line.startswith("pub struct "):
            found[name] = {b.split(" ")[1].strip(":"): b.split(" ", 2)[2].strip(",")
                           for b in body if b.startswith("pub ")}
        else:
            found[name] = [b.split()[0].strip(",") for b in body if not b.startswith("#")]
    # Declared outside the components module.
    found["ConsumeEffect::ApplyEffects"] = {"effects": "Vec<MobEffectInstance>", "probability": "f32"}
    found["ConsumeEffect::RemoveEffects"] = {"effects": "HolderSet<MobEffect, Identifier>"}
    found["ConsumeEffect::ClearAllEffects"] = {}
    found["ConsumeEffect::TeleportRandomly"] = {"diameter": "f32"}
    found["ConsumeEffect::PlaySound"] = {"sound": "SoundEvent"}
    return found


# An enum variant has no `::new()` to fill what the report leaves out.
VARIANT_DEFAULTS = {
    "ConsumeEffect::ApplyEffects": {"effects": [], "probability": 1.0},
    "ConsumeEffect::TeleportRandomly": {"diameter": 16.0},
}
# Stands in for a field the components module doesn't declare, so the
# generated file fails to compile there rather than guessing.
UNKNOWN = "FIXME_UNKNOWN_TYPE"
TAG_MODULES = {enum_name(registry): module for registry, module in TAGGED.items()}


class Values:
    """Writes a report's JSON value as the Rust expression of a type."""

    def __init__(self, types):
        self.types = types

    def rust(self, value, target):
        if isinstance(value, dict) and value:
            if target == "ConsumeEffect":
                rest = {k: v for k, v in value.items() if k != "type"}
                return self.rust(rest, f"ConsumeEffect::{to_camel_case(value['type'].split(':')[-1])}")
            if target == "MobEffectInstance":
                details = {k: v for k, v in value.items() if k != "id"}
                return (f"MobEffectInstance {{id: {self.rust(value['id'], 'MobEffect')},"
                        f"details: {self.rust(details, 'MobEffectDetails')}}}")
            if target == "AttributeModifiersEntry":
                value = {
                    **{k: v for k, v in value.items() if k not in {"amount", "type", "id", "operation"}},
                    "kind": value["type"],
                    "display": value.get("display", {}).get("type") or "default",
                    "modifier": {k: value[k] for k in ("id", "amount", "operation")},
                }
        if target is None:
            return "None"
        if target.startswith("Option<"):
            return "None" if value is None else f"Some({self.rust(value, inner(target))})"
        if target.startswith("HashMap<"):
            key, item = (t.strip() for t in inner(target).split(",", 1))
            pairs = ",".join(f"({self.rust(k, key)}, {self.rust(v, item)})" for k, v in value.items())
            return f"HashMap::from_iter([{pairs}])"
        if target == "String":
            return f'"{value}".to_owned()'
        if target == "&str":
            return self.rust(only(value), target) if isinstance(value, dict) else f'"{value}"'
        if target in NUMBERS:
            return self.rust(only(value), target) if isinstance(value, dict) and len(value) == 1 else str(value)
        if target == "EntityKind":
            entity = value.get("id") if isinstance(value, dict) else value
            if not isinstance(entity, str) or not entity.startswith("minecraft:"):
                raise ValueError(f"no entity type in {value}")
            return f"EntityKind::{variant(entity)}"
        if target == "NbtCompound":
            pairs = ",".join(f'("{k}".into(), "{v}".into())' for k, v in value.items())
            return f"NbtCompound::from_values(vec![{pairs}])"
        if isinstance(value, dict):
            return self.compound(value, target)
        if isinstance(value, bool):
            return str(value).lower()
        if isinstance(value, str):
            return self.string(value, target)
        if isinstance(value, list):
            return self.sequence(value, target)
        return str(value)

    def compound(self, value, target):
        single = len(value) == 1
        if single and (target == "Identifier" or target.startswith(("HolderSet<", "Vec<"))):
            return self.rust(only(value), target)
        if target == "ItemStack":
            item, count = self.rust(value["id"], "ItemKind"), value.get("count", 1)
            return f"ItemStack::from({item})" if count == 1 else f"ItemStack::new({item}, {count})"
        value = {**VARIANT_DEFAULTS.get(target, {}), **value}
        fields = self.types.get(target, {})
        if not value and "::" not in target:
            # A unit struct (`Glider`), else its hand-written `new()`.
            return target if target in self.types and not fields else f"{target.split('<')[0]}::new()"
        # `type` is a keyword.
        value = {"kind" if k == "type" else k: v for k, v in value.items()}
        body = "".join(f"{k}: {self.rust(v, fields.get(k, UNKNOWN))}," for k, v in value.items())
        rest = f"..{target}::new()" if len(value) < len(fields) else ""
        return f"{target} {{{body}{rest}}}"

    def string(self, value, target):
        if "Referenced(Identifier)" in self.types.get(target, []):
            return f"{target}::Referenced({self.rust(value, 'Identifier')})"
        if target.startswith("HolderSet<"):
            contents = self.rust([value], f"Vec<{target.split('<', 1)[1].split(',', 1)[0]}>")
            return f"HolderSet::Direct {{ contents: {contents} }}"
        if target.startswith(("azalea_registry::Holder<", "Holder<")):
            held = self.rust(value, target.split("<", 1)[1].split(",", 1)[0])
            return f"azalea_registry::Holder::Reference({held})"
        if target == "Identifier":
            return f'"{value}".into()'
        if target.startswith("azalea_registry::data::"):
            # TODO: a data registry's ids aren't known until a server sends
            # it, so its default entries can't be named here.
            return f"{target}::new_raw(0)"
        return f"{target}::{variant(value)}"

    def sequence(self, value, target):
        array = target.startswith("[") and target.endswith("]")
        if array:
            item = target.split(";")[0].strip("[]")
        elif "<" in target:
            item = inner(target).split(",")[0].strip()
        else:
            # A struct wrapping one list.
            fields = self.types.get(target, {})
            if len(fields) == 1 and isinstance(fields, dict):
                return self.rust(value, only(fields))
            item = None
        tags, direct = [], []
        for entry in value:
            if not (isinstance(entry, str) and entry.startswith("#minecraft:")):
                direct.append(self.rust(entry, item))
            # TODO: a tag of a data registry's entries is left empty; see
            # `string`.
            elif item not in {"BannerPatternKind", "DamageKind"}:
                tag = to_snake_case(path_of(entry)).upper()
                tags.append(f"azalea_registry::tags::{TAG_MODULES[item]}::{tag}.clone().into_iter().collect()")
        literal = f"[{','.join(direct)}]" if array else f"vec![{','.join(direct)}]"
        parts = [*tags, literal] if not tags or literal != "vec![]" else tags
        joined = parts[0] if len(parts) == 1 else f"[{','.join(parts)}].concat()"
        return f"HolderSet::Direct {{ contents: {joined} }}" if target.startswith("HolderSet<") else joined


def inner(generic):
    return generic.split("<", 1)[1].rsplit(">", 1)[0]


def only(mapping):
    return next(iter(mapping.values()))


def generate_default_components(registries, items):
    item_names = [path_of(i) for i in by_protocol_id(registries["minecraft:item"])]
    types = declared_types()
    values = Values(types)
    defaults = {}
    for item, data in items.items():
        for component, value in data["components"].items():
            defaults.setdefault(path_of(component), {})[path_of(item)] = value

    code = [GENERATED, """#![allow(clippy::all)]

use std::collections::HashMap;

use azalea_chat::translatable_component::TranslatableComponent;
use azalea_core::attribute_modifier_operation::AttributeModifierOperation;
use azalea_registry::{
    DataRegistry, HolderSet,
    builtin::{Attribute, BlockKind, EntityKind, ItemKind, MobEffect, SoundEvent},
};
use simdnbt::owned::NbtCompound;

use crate::{
    ItemStack, components::*, default_components::DefaultableComponent,
    item::consume_effect::ConsumeEffect,
};
"""]
    for component, by_item in sorted(defaults.items()):
        struct = to_camel_case(component)
        fields = types[struct]
        wrap = lambda value: value
        target, read = struct, "value"
        if len(fields) == 1 and isinstance(fields, dict):
            (field, target), = fields.items()
            wrap = lambda value, field=field: f"{struct} {{ {field}: {value} }}"
        if component == "item_name":
            target, read = "&str", "TranslatableComponent::from(value).into()"
        elif component == "item_model":
            target, read = "&str", "value.into()"
        elif component == "entity_data":
            target = "EntityKind"
            wrap = lambda value: f"{struct} {{ kind: {value}, data: NbtCompound::new() }}"
        by_item = {item: values.rust(value, target) for item, value in sorted(by_item.items())}

        counts = {}
        for value in sorted(by_item.values()):
            counts[value] = counts.get(value, 0) + 1
        common = max(counts.items(), key=lambda c: c[1])[0]
        uncommon = len(by_item) - counts[common]
        # Every item has it and most share one value: a match with a default arm.
        mostly_one = len(item_names) == len(by_item) and uncommon <= TABLE_THRESHOLD

        implements = f"impl DefaultableComponent for {struct} {{"
        if (len(by_item) > TABLE_THRESHOLD and len(counts) == 1) or (mostly_one and not uncommon):
            code += [implements,
                     "    fn default_for_item(_item: ItemKind) -> Option<Self> {",
                     f"        Some({wrap(common)})"]
        elif len(by_item) > TABLE_THRESHOLD and not mostly_one:
            table = f"{component.upper()}_VALUES"
            # A value no item uses stands for an item without the component.
            none = next(n for n in range(len(counts) + 1) if str(n) not in counts)
            row = ",".join(str(by_item.get(item, none)) for item in item_names)
            code += ["#[rustfmt::skip]",
                     f"static {table}: [{target}; {len(item_names)}] = [{row}];",
                     implements,
                     "    fn default_for_item(item: ItemKind) -> Option<Self> {",
                     f"        let value = {table}[item as usize];"]
            if len(by_item) < len(item_names):
                code += [f"        if value == {none} {{", "            return None;", "        }"]
            code.append(f"        Some({wrap(read)})")
        else:
            fallback = common if mostly_one else "return None"
            code += [implements,
                     "    fn default_for_item(item: ItemKind) -> Option<Self> {",
                     "        let value = match item {",
                     *(f"            ItemKind::{to_camel_case(item)} => {value},"
                       for item, value in by_item.items() if value != fallback),
                     f"            _ => {fallback},",
                     "        };",
                     f"        Some({wrap('value')})"]
        code += ["    }", "}"]
    write(DEFAULT_COMPONENTS, "\n".join(code))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    reference = Path(sys.argv[1])
    registries = json.loads((reference / "generated/reports/registries.json").read_text())
    data = reference / "extracted/data/minecraft"
    generate_builtin(registries)
    generate_data(data_registries(data))
    for registry, module in TAGGED.items():
        generate_tags(registries, json_tree(data / "tags" / registry), module, registry)
    # The default components are written as the hand-written types, which
    # must cover the registries just generated.
    check_menus(registries)
    check_components(registries)
    generate_default_components(registries, json_tree(reference / "generated/reports/minecraft/components/item"))


if __name__ == "__main__":
    main()
